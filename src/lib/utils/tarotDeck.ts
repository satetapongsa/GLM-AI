/**
 * Randomly draw 5 unique Tarot cards from the deck
 */
export function draw5TarotCards(): { card: TarotCard; positionLabel: string }[] {
  const shuffled = [...TAROT_DECK].sort(() => 0.5 - Math.random());
  const selected = shuffled.slice(0, 5);

  const positions = [
    "ใบที่ 1: ตัวตนและสถานการณ์ในปัจจุบัน (Current State)",
    "ใบที่ 2: อุปสรรคและสิ่งที่ซ่อนเร้น (Hidden Obstacle)",
    "ใบที่ 3: คำตอบตรงสำหรับคำถามที่ถาม (Direct Answer)",
    "ใบที่ 4: คำแนะนำและแนวทางแก้ไข (Actionable Advice)",
    "ใบที่ 5: ภาพรวมและทิศทางสรุปอนาคต (Overall Outcome)",
  ];

  return selected.map((card, idx) => ({
    card,
    positionLabel: positions[idx],
  }));
}
